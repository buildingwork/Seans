export interface WikiData {
  title: string;
  extract: string;
  thumbnailUrl?: string;
  pageUrl: string;
}

export async function fetchWikipediaSummary(wikiTitle: string, fallback: FamousSean): Promise<WikiData> {
  try {
    const encodedTitle = encodeURIComponent(wikiTitle.replace(/ /g, '_'));
    const res = await fetch(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodedTitle}`, {
      headers: {
        'Accept': 'application/json',
      },
    });

    if (res.ok) {
      const data = await res.json();
      return {
        title: data.title || fallback.name,
        extract: data.extract || fallback.summary,
        thumbnailUrl: data.thumbnail?.source || fallback.imageUrl,
        pageUrl: data.content_urls?.desktop?.page || `https://en.wikipedia.org/wiki/${encodedTitle}`,
      };
    }
  } catch {
    // network or cors fallback
  }

  return {
    title: fallback.name,
    extract: fallback.summary,
    thumbnailUrl: fallback.imageUrl,
    pageUrl: `https://en.wikipedia.org/wiki/${encodeURIComponent(wikiTitle)}`,
  };
}
